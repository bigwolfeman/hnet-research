"""Generate ignored/ref/refnet: the reference `hnet` package renamed, so it can share a process with our `hnet`.

Pseudocode:
    src = ignored/ref/hnet/hnet  (goombalab/hnet, commit must equal PINNED)
    for each .py under src: rewrite "from hnet." -> "from refnet." and "import hnet" -> "import refnet"
    assert no other absolute reference to the package name remains; write to ignored/ref/refnet (replaced whole)

usage: python vendor_refnet.py
"""
from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
REF = ROOT / "ignored" / "ref" / "hnet"
OUT = ROOT / "ignored" / "ref" / "refnet"
PINNED = "3673fe1"


def main():
    rev = subprocess.check_output(["git", "-C", str(REF), "rev-parse", "--short", "HEAD"]).decode().strip()
    assert rev == PINNED, f"reference clone is at {rev}, expected {PINNED}"
    if OUT.exists():
        shutil.rmtree(OUT)
    n = 0
    for src in sorted((REF / "hnet").rglob("*.py")):
        text = src.read_text()
        new = re.sub(r"^(\s*)from hnet\.", r"\1from refnet.", text, flags=re.M)
        new = re.sub(r"^(\s*)import hnet\b", r"\1import refnet", new, flags=re.M)
        left = [l for l in new.splitlines() if re.match(r"\s*(from|import) hnet\b", l)]
        assert not left, f"{src}: unrewritten imports {left}"
        dst = OUT / src.relative_to(REF / "hnet")
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(f"# GENERATED by {Path(__file__).name} from goombalab/hnet@{PINNED}: {src.relative_to(REF)}\n" + new)
        n += 1
    print(f"wrote {n} files to {OUT}")


if __name__ == "__main__":
    main()
